#[test]
fn conventional_id_auto_increment_primary_key_is_supported() {
    let dir = tempfile::tempdir().unwrap();
    let db = Db::create(dir.path().join("conventional-id.esql")).unwrap();
    db.query("CREATE TABLE users (id int AUTO_INCREMENT PRIMARY KEY, name text NOT NULL)")
        .unwrap();
    let (columns, returned) = rows(
        db.query("INSERT INTO users (name) VALUES ('Ada') RETURNING id, name")
            .unwrap(),
    );
    assert_eq!(columns, vec!["id", "name"]);
    assert_eq!(
        returned,
        vec![vec![Value::Int64(1), Value::Text("Ada".into())]]
    );
    assert_eq!(
        rows(db.query("SELECT id, name FROM users WHERE id = 1").unwrap()).1,
        vec![vec![Value::Int64(1), Value::Text("Ada".into())]]
    );
    assert_eq!(
        rows(db.query("SELECT * FROM users").unwrap()),
        (
            vec!["id".into(), "name".into()],
            vec![vec![Value::Int64(1), Value::Text("Ada".into())]],
        )
    );
    db.query("UPDATE users SET name = 'Grace' WHERE id = 1")
        .unwrap();
    assert_eq!(
        rows(db.query("SELECT id, name FROM users").unwrap()).1,
        vec![vec![Value::Int64(1), Value::Text("Grace".into())]]
    );
    db.query("DELETE FROM users WHERE id = 1").unwrap();
    assert!(rows(db.query("SELECT id FROM users").unwrap()).1.is_empty());
}

#[test]
fn declared_id_can_be_the_target_of_a_foreign_key() {
    let dir = tempfile::tempdir().unwrap();
    let db = Db::create(dir.path().join("declared-id-fk.esql")).unwrap();
    db.query("CREATE TABLE parents (id int AUTO_INCREMENT PRIMARY KEY, name text)")
        .unwrap();
    db.query("CREATE TABLE children (parent_id int REFERENCES parents(id), name text)")
        .unwrap();
    db.query("INSERT INTO parents (name) VALUES ('parent')")
        .unwrap();
    db.query("INSERT INTO children (parent_id, name) VALUES (1, 'child')")
        .unwrap();
    assert_eq!(
        rows(
            db.query("SELECT children.name FROM children JOIN parents ON children.parent_id = parents.id")
                .unwrap(),
        )
        .1,
        vec![vec![Value::Text("child".into())]]
    );
}

